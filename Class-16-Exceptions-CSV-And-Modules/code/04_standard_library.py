# The standard library: modules that come with Python. No install needed.
import math
import random
import datetime
import os
import uuid

print(math.sqrt(49))           # 7.0
print(random.randint(1, 6))    # any number from 1 to 6
print(datetime.date.today())   # today's date
print(os.getcwd())             # the folder the program runs in
print(uuid.uuid4())            # a unique ID, different every time
