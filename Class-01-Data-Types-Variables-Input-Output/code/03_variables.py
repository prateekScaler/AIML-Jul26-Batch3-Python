# A variable is a name that refers to a value.
# Four values, four basic data types.

name = "Kishor"      # str   - text, inside quotes
age = 25              # int   - whole number
height = 5.8          # float - number with a decimal point
is_student = True     # bool  - True or False (capital first letter)

print(name)
print(age)
print(height)
print(is_student)
