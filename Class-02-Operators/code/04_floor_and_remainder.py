# // and % are two halves of one division.

print(10 // 3)   # 3  each friend gets ₹3
print(10 % 3)    # 1  ₹1 is left over

# A ₹450 dinner bill, split among 4
print(450 // 4)  # 112
print(450 % 4)   # 2

# % is the standard test for "divides evenly"
print(14 % 2)      # 0 -> even
print(15 % 2)      # 1 -> odd
print(2550 % 100)  # 50 -> an ATM with only ₹100 notes cannot give ₹2,550
