# Comparison operators ask a question. The answer is always True or False.

print(10 > 5)     # True
print(10 < 5)     # False
print(10 == 10)   # True
print(10 != 10)   # False
print(5 >= 5)     # True
print(3 <= 2)     # False

# The answer can be stored like any other value
age = 20
is_adult = age >= 18
print(is_adult)   # True
