# Arithmetic operators

a = 10
b = 3

print(a + b)    # 13
print(a - b)    # 7
print(a * b)    # 30   (* not ×)
print(a / b)    # 3.3333333333333335   / always gives a float
print(15 / 5)   # 3.0  even when it divides evenly
print(a // b)   # 3    floor division: the whole share
print(a % b)    # 1    modulus: what is left over
print(2 ** 3)   # 8    power: 2 × 2 × 2

